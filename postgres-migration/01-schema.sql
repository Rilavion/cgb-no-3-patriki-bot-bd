-- Сайт видит настройки только для администратора. Секретный токен здесь
-- никогда не хранится: он остаётся только в EnvironmentFile на VPS.

create or replace function public.tg_queue_application()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_kind text;
  v_key text;
begin
  if tg_op = 'INSERT' then
    v_kind := 'created';
    v_key := 'applications:' || new.id::text || ':created';
  elsif new.status is distinct from old.status then
    v_kind := 'status_' || coalesce(new.status, 'unknown');
    v_key := 'applications:' || new.id::text || ':' || v_kind || ':' || txid_current()::text;
  else
    return new;
  end if;

  insert into public.telegram_notifications
    (event_key, route_key, event_kind, source_table, source_id, payload)
  values (
    v_key, 'applications', v_kind, 'applications', new.id::text,
    jsonb_build_object(
      'id', new.id, 'app_type', new.app_type,
      'submitter_name', new.submitter_name,
      'submitter_discord', new.submitter_discord,
      'status', new.status, 'reject_reason', new.reject_reason,
      'responded_by_name', new.responded_by_name,
      'created_at', new.created_at, 'responded_at', new.responded_at
    )
  ) on conflict (event_key) do nothing;
  return new;
end;
$$;

drop trigger if exists tg_applications_notify on public.applications;
create trigger tg_applications_notify
after insert or update of status on public.applications
for each row execute function public.tg_queue_application();

-- Заявки персонала. Маршруты соответствуют темам, указанным заказчиком.
create or replace function public.tg_queue_request()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_route text;
  v_kind text;
  v_key text;
begin
  v_route := case new.kind
    when 'promotion' then 'promotion'
    when 'restoration' then 'applications'
    when 'dismissal' then 'dismissal'
    when 'vacation_ic' then 'vacations'
    when 'vacation_ooc' then 'vacations'
    when 'leave' then 'leave'
    else null
  end;
  if v_route is null then return new; end if;

  if tg_op = 'INSERT' then
    v_kind := 'created';
    v_key := 'requests:' || new.id::text || ':created';
  elsif new.status is distinct from old.status then
    v_kind := 'status_' || coalesce(new.status, 'unknown');
    v_key := 'requests:' || new.id::text || ':' || v_kind || ':' || txid_current()::text;
  else
    return new;
  end if;

  insert into public.telegram_notifications
    (event_key, route_key, event_kind, source_table, source_id, payload)
  values (
    v_key, v_route, v_kind, 'requests', new.id::text,
    jsonb_build_object(
      'id', new.id, 'code', new.code, 'kind', new.kind,
      'values', coalesce(new.values, '{}'::jsonb),
      'submitter_fio', new.submitter_fio,
      'submitter_static', new.submitter_static,
      'submitter_discord', new.submitter_discord,
      'status', new.status, 'verdict_comment', new.verdict_comment,
      'verdict_by_name', new.verdict_by_name,
      'created_at', new.created_at, 'verdict_at', new.verdict_at
    )
  ) on conflict (event_key) do nothing;
  return new;
end;
$$;

