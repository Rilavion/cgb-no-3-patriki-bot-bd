-- 2.1 Назначение роли пользователю (ЛК → «Создать аккаунт» / смена роли).
-- v3: p_role опционален — если пуст/null, базовая роль берётся из
-- переданной кастомной роли (p_custom_role_id → custom_roles.base_role),
-- иначе 'user'. Возвращает json с фактически записанной ролью.
drop function if exists public.staff_upsert_role(uuid, text, text, uuid);
create function public.staff_upsert_role(
  p_user_id uuid, p_role text default null, p_display_name text default null, p_custom_role_id uuid default null
) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_cr public.custom_roles%rowtype;
  v_role text;
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;
  if not exists (select 1 from public.user_roles ur where ur.user_id = auth.uid() and ur.role = 'admin')
     and exists (select 1 from public.user_roles where role = 'admin') then
    raise exception 'only admin can assign roles';
  end if;
  if p_custom_role_id is not null then
    select * into v_cr from public.custom_roles where id = p_custom_role_id;
  end if;
  v_role := coalesce(nullif(trim(coalesce(v_cr.base_role,'')),''), nullif(trim(coalesce(p_role,'')),''), 'user');
  insert into public.user_roles (user_id, role, display_name, custom_role_id, updated_at)
  values (p_user_id, v_role, nullif(p_display_name,''), v_cr.id, now())
  on conflict (user_id) do update
    set role = excluded.role,
        display_name = coalesce(excluded.display_name, public.user_roles.display_name),
        custom_role_id = excluded.custom_role_id,
        updated_at = now();
  return json_build_object('ok', true, 'user_id', p_user_id, 'role', v_role,
    'custom_role_id', v_cr.id, 'custom_role_key', v_cr.key, 'custom_role_name', v_cr.name);
end $$;

